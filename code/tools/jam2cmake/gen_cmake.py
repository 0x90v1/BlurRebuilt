#!/usr/bin/env python3
"""
gen_cmake.py — turn the jamextract JSON into cmake/targets.cmake.

Usage: python gen_cmake.py --json _work/build/targets_pc_speed.json --out cmake/targets.cmake
       [--shaders-dir _work/build/gen/shaders]

The root CMakeLists.txt defines the global flags, the vendor variables
(BLUR_DXSDK_INCLUDE, BLUR_D3DX9_LIB, BLUR_OPENAL_INCLUDE, BLUR_OPENAL_LIB,
BLUR_JPEG_DIR) and the shim targets (blur_jpeg, blur_shims), then includes
the generated file.
"""
import argparse
import glob
import json
import os
import re

# include-dir placeholders from the jamfiles -> cmake variables (None = drop)
INCLUDE_MAP = [
    (re.compile(r'\$\{DXSDK_PATH\}/?include', re.I), '${BLUR_DXSDK_INCLUDE}'),
    (re.compile(r'libs/vendor/openal/1\.1/include', re.I), '${BLUR_OPENAL_INCLUDE}'),
    (re.compile(r'libs/vendor/jpeg/version62/include', re.I), '${BLUR_JPEG_DIR}'),
    (re.compile(r'libs/vendor/bink', re.I), None),
    (re.compile(r'libs/vendor/massive', re.I), None),
    (re.compile(r'Code/Genesis', re.I), None),
]

# libraries in LinkLibraries that are not extracted targets
LINK_SKIP = re.compile(r'bink|massive', re.I)
LINK_MAP = {'jpeg': 'blur_jpeg'}


def cm(path):
    return path.replace('\\', '/')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--shaders-dir', default='_work/build/gen/shaders')
    ap.add_argument('--unity-dir', default='_work/build/gen/unity')
    ap.add_argument('--blobs-dir', default='_work/build/gen/blobs')
    ap.add_argument('--no-unity', dest='unity', action='store_false', help='compile Batch members individually')
    # The engine libraries compile clean per file and hit unity-only clashes
    # (headers without guards, namespace pollution); the game libraries need
    # the unity build (cross-file templates, headers relying on earlier files).
    ap.add_argument('--unity-targets', default=r'^(Amax|amax_\w+)$', help='regex of targets built as unity units')
    a = ap.parse_args()
    d = json.load(open(a.json, encoding='utf-8'))
    top = d['config']['top']
    targets = [t for t in d['targets'] if t['supported']]
    names = {t['name'].lower(): t['name'] for t in targets}

    L = ['# Generated by code/tools/jam2cmake/gen_cmake.py from ' + cm(os.path.relpath(a.json, top)) + ' - do not edit',
         '# Regenerate: python code/tools/jam2cmake/jamextract.py ... && python code/tools/jam2cmake/gen_cmake.py ...',
         '']
    missing_inc = set()
    unity_dir = os.path.join(top, a.unity_dir)
    os.makedirs(unity_dir, exist_ok=True)
    # Embedded blobs the original build linked as binary objects. The build
    # stamp is read by Debug::GetBuildTime/Date/User/Pc/Version/Revision as
    # whitespace-separated words 0..6 (BuildStamp.cpp writes NULs into it, so
    # it must be writable). The Lua bundle comes from luabundle.py.
    blobs_dir = os.path.join(top, a.blobs_dir)
    os.makedirs(blobs_dir, exist_ok=True)
    import datetime
    now = datetime.datetime.now()
    stamp = f'{now:%H:%M:%S} {now:%Y-%m-%d} blur2pc {os.environ.get("COMPUTERNAME", "pc")} local Change 0\r\n'
    stamp_cpp = os.path.join(blobs_dir, 'buildstamp.cpp')
    stamp_text = ('// Generated by gen_cmake.py: build stamp blob (Debug::GetBuildTime and friends)\n'
                  'extern "C" {\n'
                  f'extern char _binary_buildstamp_txt_start[] = "{stamp.encode("unicode_escape").decode()}";\n'
                  'extern char _binary_buildstamp_txt_end[1] = { 0 };\n}\n')
    if not os.path.exists(stamp_cpp):
        with open(stamp_cpp, 'w', encoding='ascii', newline='\n') as fh:
            fh.write(stamp_text)
    blob_sources = [cm(os.path.join(a.blobs_dir, 'buildstamp.cpp'))]
    lua_cpp = os.path.join(blobs_dir, 'amax_lua_bundle.cpp')
    if os.path.exists(lua_cpp):
        blob_sources.append(cm(os.path.join(a.blobs_dir, 'amax_lua_bundle.cpp')))
    else:
        print('note: no Lua bundle yet; run luabundle.py then gen_cmake.py again')
    for t in targets:
        name = t['name']
        srcs = [cm(s) for s in t['sources']]
        # Jam's [ Batch ... ] groups were compiled as one translation unit each.
        # Reproduce that with a generated unity file per group; the member
        # files are then not compiled individually.
        if a.unity and t.get('batches') and re.match(a.unity_targets, name):
            batched = set()
            for i, b in enumerate(t['batches']):
                if len(b['files']) < 2:
                    continue
                ufile = f'{name}_batch{i + 1}.cpp'
                lines = [f'// Generated by gen_cmake.py: unity unit reproducing Jam "Batch" group {i + 1} of target {name}',
                         f'// {len(b["files"])} files, PCH {b["pch"]}', '']
                for f in b['files']:
                    lines.append(f'#include "{cm(os.path.join(top, f))}"')
                    batched.add(cm(f).lower())
                upath = os.path.join(unity_dir, ufile)
                text = '\n'.join(lines) + '\n'
                if not (os.path.exists(upath) and open(upath, encoding='ascii').read() == text):
                    with open(upath, 'w', encoding='ascii', newline='\n') as fh:
                        fh.write(text)
                srcs.append(cm(os.path.join(a.unity_dir, ufile)))
            srcs = [s for s in srcs if s.lower() not in batched]
        shader_cpp = os.path.join(a.shaders_dir, f'{name}_shaders.cpp')
        if t['shaders'] and os.path.exists(os.path.join(top, shader_cpp)):
            srcs.append(cm(shader_cpp))
        if t['kind'] == 'application':
            L.append(f'add_executable({name} WIN32')
            srcs += blob_sources
        else:
            L.append(f'add_library({name} STATIC')
        for s in srcs:
            L.append(f'    ${{BLUR_TOP}}/{s}')
        L.append(')')
        # include dirs. Jam compiled from the target's own directory, so bare
        # includes like "CorePch.h" resolved against it: add it first.
        incs = [f'${{BLUR_TOP}}/{cm(t["dir"])}']
        for i in t['includes']:
            p = cm(i['path'])
            mapped = p
            dropped = False
            for rx, rep in INCLUDE_MAP:
                if rx.search(p):
                    mapped = rep
                    dropped = rep is None
                    break
            if dropped:
                continue
            if mapped == p:
                if not i['exists']:
                    missing_inc.add(p)
                    continue
                mapped = f'${{BLUR_TOP}}/{p}'
            if mapped not in incs:
                incs.append(mapped)
        if incs:
            L.append(f'target_include_directories({name} PRIVATE')
            for i in incs:
                L.append(f'    {i}')
            L.append(')')
        defs = []
        for x in t['defines']:
            if x not in defs:
                defs.append(x)
        if defs:
            L.append(f'target_compile_definitions({name} PRIVATE {" ".join(defs)})')
        # PCH
        pch = t['pch_source']
        if pch:
            hdr = os.path.splitext(pch)[0] + '.h'
            if not os.path.exists(os.path.join(top, hdr)):
                # stale jamfile (amax_kanzen names StdAfx.cpp, files are Kanzen_PCH.*)
                cands = glob.glob(os.path.join(top, t['dir'], '*[Pp][Cc][Hh].h'))
                hdr = cm(os.path.relpath(cands[0], top)) if cands else None
            if hdr:
                L.append(f'target_precompile_headers({name} PRIVATE ${{BLUR_TOP}}/{cm(hdr)})')
                csrc = [s for s in srcs if s.lower().endswith('.c')]
                if csrc:
                    L.append(f'set_source_files_properties(')
                    for s in csrc:
                        L.append(f'    ${{BLUR_TOP}}/{s}')
                    L.append('    PROPERTIES SKIP_PRECOMPILE_HEADERS ON)')
        # per-file defines
        for od in d['object_defines']:
            for f, g in zip(od['files'], od.get('grists', [''] * len(od['files']))):
                if g:
                    continue  # define belonged to a gristed (SPU module) object, not the library's copy
                if cm(f) in srcs:
                    L.append(f'set_source_files_properties(${{BLUR_TOP}}/{cm(f)} PROPERTIES COMPILE_DEFINITIONS "{";".join(od["defines"])}")')
        L.append(f'set_target_properties({name} PROPERTIES FOLDER "{cm(os.path.dirname(t["dir"]))}")')
        if t['kind'] == 'application':
            libs = []
            for l in t['link_libraries']:
                if LINK_SKIP.search(l):
                    continue
                key = os.path.basename(l).lower()
                if key in LINK_MAP:
                    libs.append(LINK_MAP[key])
                elif key in names:
                    libs.append(names[key])
                else:
                    L.append(f'# unresolved link library: {l}')
            L.append(f'target_link_libraries({name} PRIVATE')
            for l in libs:
                L.append(f'    {l}')
            L.append('    ${BLUR_SYSTEM_LIBS}')
            L.append(')')
            flags = [f for f in t['linkflags_final'] if not f.startswith('/MACHINE') and f != '/DEBUG']
            L.append(f'target_link_options({name} PRIVATE {" ".join(flags)})')
        L.append('')

    with open(a.out, 'w', encoding='ascii', newline='\n') as fh:
        fh.write('\n'.join(L))
    print(f'wrote {a.out}: {len(targets)} targets')
    if missing_inc:
        print('dropped missing include dirs:')
        for m in sorted(missing_inc):
            print('   ', m)


if __name__ == '__main__':
    main()
