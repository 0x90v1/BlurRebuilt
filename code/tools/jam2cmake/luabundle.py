#!/usr/bin/env python3
"""
luabundle.py — build the Lua script bundle that Jam's `LUABundle Amax : $(LUASRC) : <root>`
rule produced and the game links as `_binary_Amax_LUA_bin_start`.

Layout (little-endian; see mercury/library/ui/source/ui/Game/UILua.cpp C_UILua::Init,
SetCurrentPAK and GetLuaPAKData):
    char[4]  "IUZB"            -- *(DWORD*) == 'BZUI' on a little-endian build
    int32    count
    LUA_SCREEN_INFO[count]     -- {nameOffset, dataOffset, compressedSize, uncompressedSize},
                                  offsets relative to the string table below
    string table               -- NUL-terminated names, root-relative with backslashes ("Screens\\GuiBank.lua")
    data                       -- each script as a zlib stream (inflateInit, so with the zlib header)

Usage: python luabundle.py --json _work/build/targets_pc_speed.json --out _work/build/gen/blobs/amax_lua_bundle.cpp
"""
import argparse
import json
import os
import struct
import sys
import zlib


def build(scripts, root):
    names, blobs = [], []
    for s in scripts:
        rel = os.path.relpath(s, root).replace('/', '\\')
        data = open(s, 'rb').read()
        names.append(rel)
        blobs.append((zlib.compress(data, 9), len(data)))
    strtab = bytearray()
    name_off = []
    for n in names:
        name_off.append(len(strtab))
        strtab += n.encode('latin-1') + b'\0'
    # data follows the string table; offsets are relative to the string table start
    data = bytearray()
    recs = []
    for (name_o, (comp, usize)) in zip(name_off, blobs):
        off = len(strtab) + len(data)
        recs.append(struct.pack('<iiii', name_o, off, len(comp), usize))
        data += comp
    out = b'IUZB' + struct.pack('<i', len(names)) + b''.join(recs) + bytes(strtab) + bytes(data)
    return out, names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    d = json.load(open(a.json, encoding='utf-8'))
    top = d['config']['top']
    b = d['lua_bundles'][0]
    root = os.path.join(top, b['root'])
    scripts = [os.path.join(top, s) for s in b['scripts']]
    blob, names = build(scripts, root)
    words = struct.unpack('<%dI' % ((len(blob) + 3) // 4), blob + b'\0' * ((-len(blob)) % 4))
    lines = [f'// Generated by code/tools/jam2cmake/luabundle.py: {len(names)} Lua scripts, {len(blob)} bytes',
             '// Symbol layout: see luabundle.py / C_UILua::Init',
             'extern "C" {',
             f'extern const unsigned int _binary_{b["target"]}_LUA_bin_start[{len(words)}] = {{']
    for i in range(0, len(words), 12):
        lines.append('    ' + ', '.join(f'0x{x:08x}' for x in words[i:i + 12]) + ',')
    lines.append('};')
    lines.append(f'extern const unsigned int _binary_{b["target"]}_LUA_bin_end[1] = {{ 0 }};')
    lines.append('}')
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w', encoding='ascii', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f'{a.out}: {len(names)} scripts, {len(blob)} bytes; e.g. {names[:3]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
