SpawnProcess *FarmingWorker::s_Process = NULL;

FarmingWorker::FarmingWorker() :
		m_State(StateFree),
		m_CmdPtr(0)
{
	m_pQueueSubscriber = new QueueSubscriber();
	Debug::GetRootLogger().AddSubscriber( m_pQueueSubscriber );
	m_pRepeaterServer = new Debug::RepeaterServer( 825 );
	m_pRepeaterServer->Start();
	m_iIdleMessageCounter = 0;
}

FarmingWorker::~FarmingWorker()
{
	m_pRepeaterServer->Stop();
	delete m_pRepeaterServer;
	StopProcess();
}

bool FarmingWorker::OnStart()
{
	if (!AnnounceMachine("WORKER"))
		return false;

	m_State = (s_Process) ? StateOccupied : StateFree;

	return true;
}

bool FarmingWorker::OnStop()
{
	return Send("QUIT");
}

bool FarmingWorker::OnCommand(const char* Command)
{
	if (!strnicmp(Command, "JOB ", 4))
	{
		if (m_State == StateFree)
		{
			m_State = StateAccepted;

			m_Command	= Command + 4;
			m_CmdPtr	= m_Command;

			StartProcess();

			if (!Send("ACCEPTED"))
				return false;
		}
		else
		{
			if (!Send("IGNORED"))
				return false;
		}
	}
	else if (!stricmp(Command, "KILL"))
	{
		if (m_State == StateAccepted)
		{
			StopProcess();

			m_State = StateFree;

			if (!Send("CANCELLED"))
				return false;
		}
		else
		{
			/*	-- no change in the worker's status, so no need to send anything
			if (!Send("IGNORED KILL"))
				return false;
			(*/
		}
	}
	else
	{
		LOGDEBUG( xFarm::g_Log, "%s: unrecognized command %s\n", m_Process->GetMyUserName(), Command);
		return false;
	}

	return true;
}

// send a log event across the network to the farm server
void FarmingWorker::SendLogEvent(Debug::LogEvent *pEvent)
{
	// create message packet containing the log event
	Sys::C_MemoryStream buffer(4096);
	Sys::BinarySerialiser<Ut::NoEndianSwap> msg(buffer);

	msg << *pEvent;

	U32 cData = buffer.GetBufferSize();
	U32 c = htonl(cData);

	m_Mutex.Wait();

	// tell the server a log event is coming
	// send the header + message body
	Send("LOG");
	U8 *pData = new U8[cData + sizeof(c)];
	memcpy(pData, &c, sizeof(c));
	memcpy(pData + sizeof(c), buffer.GetBufferPtr(), cData);
	SendRAW(pData, cData + sizeof(c));

	m_Mutex.Release();
}

// retrieve the log data and send it to the server
bool FarmingWorker::UpdateLog()
{
	bool bDidSomething = false;

	// are there any log events to send?
	Debug::LogEvent event;
	while (m_pQueueSubscriber->PopFront(&event))
	{
/*
		// ensure that messages generated by the farm worker itself are not sent across the network
		static const Util::C_String sHostName = Network::GetHostName();
		if (event.pid == MT::GetProcessID() && event.host == sHostName)
			continue;
*/
		SendLogEvent( &event );
		bDidSomething = true;
	}

	return bDidSomething;
}

bool FarmingWorker::OnIdle()
{
	if ((m_State == StateOccupied) || (m_State == StateAccepted))
	{
		if (IsProcessAlive())
		{
			if (!UpdateLog())
			{
				m_iIdleMessageCounter++;
				if (m_iIdleMessageCounter == 10)
				{
					m_iIdleMessageCounter = 0;
					if (!Send("BUSY"))
						return false;
				}
			}
		}
		else
		{
			if (m_CmdPtr && *m_CmdPtr)
			{
				StopProcess();

				StartProcess();
			}
			else
			{
				if (m_State == StateAccepted)
				{
					// go back into idle for a couple of seconds, so we have time to receive pending debug messages
					m_State = StateWaitingToFinish;
				}
				else
				{
					m_iIdleMessageCounter++;
					if (m_iIdleMessageCounter == 10)
					{
						m_iIdleMessageCounter = 0;
						if (!Send("FREE"))
							return false;
					}

					m_State = StateFree;

					StopProcess();
				}
			}
		}
	}
	else if (m_State == StateWaitingToFinish)
	{
		// update log to server
		UpdateLog();

		// get process exit code to detemine whether the job completed of failed
		int dwExitCode = -1;
		if (s_Process)
			dwExitCode = s_Process->GetExitCode();

		if (dwExitCode == 0)
		{
			// send "job finished" command to the server
			if (!Send("FINISHED"))
				return false;
		}
		else
		{
			// send "job failed" command to the server
			if (!Send("FAILED"))
				return false;
		}

		m_State = StateFree;

		StopProcess();
	}
	else
	{
		if (!UpdateLog())
		{
			if (!Send("FREE"))
				return false;
		}

	}

	return true;
}

int FarmingWorker::GetIdleTime() const
{
	return 250;
}

void FarmingWorker::StartProcess()
{
	while(*m_CmdPtr)
	{
		char Buffer[4096];
		char* Ptr;

		for(Ptr = Buffer; *m_CmdPtr && (Ptr < (Buffer + sizeof(Buffer) - 1)); )
		{
			if (strnicmp(m_CmdPtr, "$$next$$", 8) == 0)
			{
				m_CmdPtr += strlen("$$next$$");
				break;
			}
			else
				*Ptr++ = *m_CmdPtr++;
		}

		*Ptr = '\0';

		if (*Buffer)
		{
			s_Process = new SpawnProcess(Buffer);
			s_Process->Start();
		}
	}
}

void FarmingWorker::StopProcess()
{
	if (s_Process)
	{
		s_Process->Terminate();
		delete s_Process;
		s_Process = NULL;
	}
}

bool FarmingWorker::IsProcessAlive() const
{
	if (s_Process == NULL)
		return false;

	return s_Process->IsRunning();
}
